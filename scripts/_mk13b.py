A('        ("输出 .i", "约 1750 行", GREEN, 9.0),')
A('    ]')
A('    for name, desc, color, x in stages:')
A('        ax.add_patch(Rectangle((x, 5.1), 2.5, 1.1, facecolor=color,')
A('                               edgecolor=DARK, lw=1.2))')
A('        ax.text(x + 1.25, 5.85, name, ha="center", va="center",')
A('                fontsize=8.8, color=TEXT, fontweight="bold")')
A('        ax.text(x + 1.25, 5.42, desc, ha="center", va="center",')
A('                fontsize=7.4, color=TEXT)')
