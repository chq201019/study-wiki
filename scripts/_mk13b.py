A('    ax.text(0.4, 6.9, "HEAD 是个「指向引用的引用」", fontsize=9.2,')
A('            fontweight="bold", color=TEXT)')
A('    ax.text(0.4, 6.55, "cat .git/HEAD  →  ref: refs/heads/main", fontsize=8,')
