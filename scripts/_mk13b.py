A('    ax.text(0.4, 2.6, "三个操作的本质", fontsize=9.6, fontweight="bold", color=TEXT)')
A('    rows = [')
A('        ("切换分支", "只改 HEAD 里那一行指向", GREEN),')
A('        ("提交", "新建 commit 对象，改分支文件里的 SHA", BLUE),')
A('        ("reset --hard", "只移动指向，旧 commit 还在（能被 reflog 找回）", ORANGE),')
A('    ]')
A('    for i, (k, v, c) in enumerate(rows):')
A('        y = 2.2 - i * 0.45')
A('        ax.add_patch(Rectangle((0.6, y - 0.14), 0.24, 0.28, facecolor=c,')
A('                               edgecolor=DARK, lw=0.8))')
A('        ax.text(1.0, y, k, fontsize=8.6, color=TEXT, va="center", fontweight="bold")')
A('        ax.text(2.6, y, v, fontsize=8.2, color=TEXT, va="center")')
A('')
A('    ax.text(0.4, 0.5,')
A('            "所以分支切换是 O(1) —— 不涉及任何文件内容重算。这是 Git 快的根本原因。",')
A('            fontsize=8.2, color=LINE)')
A('    ax.text(0.4, 0.15,')
