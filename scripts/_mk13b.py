A('')
A('    ax.text(0.4, 4.5, "为什么 .i 有 1750 行", fontsize=9.4, fontweight="bold", color=TEXT)')
A('    ax.text(0.4, 4.15,')
A('            "stdio.h 会递归带进几十个头文件 —— 你只写了 10 行，但编译器看到的是几千行。",')
A('            fontsize=8.2, color=TEXT)')
A('')
A('    ax.text(0.4, 3.5, "四个容易踩的坑", fontsize=9.4, fontweight="bold", color=RED)')
