A('    ]')
A('    for i, s in enumerate(pts):')
A('        ax.text(0.4, 3.1 - i * 0.36, s, fontsize=8, color=TEXT)')
A('')
A('    ax.text(0.4, 1.4, "验证手段", fontsize=9.2, fontweight="bold", color=TEXT)')
