A('# ---------- C 预处理流程 ----------')
A('def c_preprocess():')
A('    fig, ax = plt.subplots(figsize=(10.8, 6.2))')
A('    ax.set_xlim(0, 13.6)')
A('    ax.set_ylim(0, 7.6)')
A('    ax.set_axis_off()')
A('    ax.text(0.2, 7.2, "C 预处理：纯文本替换，没有任何语法理解",')
A('            fontsize=12.5, fontweight="bold", color=TEXT)')
A('')
A('    stages = [')
A('        ("源文件", "main.c（10 行）", BLUE, 0.6),')
