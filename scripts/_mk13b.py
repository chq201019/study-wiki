A('    ax.set_xlim(0, 13.6)')
A('    ax.set_ylim(0, 7.8)')
A('    ax.set_axis_off()')
A('    ax.text(0.2, 7.4, "Git 分支只是一个存着 SHA 的文件", fontsize=12.5,')
A('            fontweight="bold", color=TEXT)')
A('')
A('    # 提交链')
A('    commits = [("c1", 1.4), ("c2", 3.4), ("c3", 5.4), ("c4", 7.4)]')
A('    for name, x in commits:')
A('        ax.add_patch(plt.Circle((x, 5.2), 0.42, facecolor=BLUE,')
A('                                edgecolor=DARK, lw=1.4))')
A('        ax.text(x, 5.2, name, ha="center", va="center", fontsize=8, color=TEXT)')
A('        if name != "c1":')
A('            arrow(ax, (x - 0.85, 5.2), (x - 0.45, 5.2), color=LINE, lw=1.4)')
A('')
A('    # main 分支指针')
A('    ax.annotate("", xy=(7.4, 5.75), xytext=(7.4, 5.7),')
A('                arrowprops=dict(arrowstyle="-|>", color=RED, lw=1.6))')
A('    box(ax, 6.5, 5.95, 1.8, 0.55, "main", None, GREEN, fs=8.6)')
A('    ax.text(8.5, 6.22, "指向 c4", fontsize=7.6, color=RED, va="center")')
A('')
A('    # feature 分支')
A('    ax.add_patch(plt.Circle((7.4, 3.6), 0.42, facecolor=PINK,')
A('                            edgecolor=DARK, lw=1.4))')
A('    ax.text(7.4, 3.6, "f1", ha="center", va="center", fontsize=8, color=TEXT)')
