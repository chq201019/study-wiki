A('')
A('    steps = [')
A('        ("① 收集候选", "所有名为 operator+ 的函数", ORANGE, "成员 + 非成员 + 内建"),')
A('        ("② 模板推导", "为每个候选推出具体类型", PINK, "失败就剔除（SFINAE）"),')
A('        ("③ 可行函数", "参数能转换过去的留下", PURPLE, "看隐式转换序列"),')
